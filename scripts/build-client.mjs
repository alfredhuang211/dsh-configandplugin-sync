/**
 * Builds the browser half of dsh-configandplugin-sync.
 *
 * The Harness Web module table hands a client plugin a `window.__ModuleLoader__`
 * factory whose only externals are the table's react entries. This script
 * bundles `client/src/index.tsx` to CommonJS with react left external, then
 * wraps the bundle in that exact factory form:
 *
 *   window.__ModuleLoader__.load({ id: '<package name>', factory(require) { ... } });
 *
 * Keeping react external is mandatory: a second React copy in the page breaks
 * hooks, and the module table already provides the shared instance. The script
 * also fails the build if the bundle requires anything outside the module table
 * (a stray import from the Host's `src/**` would break the page at load time).
 */
import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Modules the Harness module table provides to a client bundle. */
const EXTERNALS = ['react', 'react-dom', 'react/jsx-runtime', 'react-dom/client']

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const outfile = join(root, 'lib', 'client.js')

const result = await build({
  entryPoints: [join(root, 'client/src/index.tsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  jsx: 'automatic',
  // Keep the zh/en dictionaries readable in the emitted artifact: the host
  // serves UTF-8, and a searchable label makes the generated file debuggable.
  charset: 'utf8',
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  logLevel: 'warning',
})

const bundled = result.outputFiles[0]?.text
if (bundled === undefined) throw new Error('client bundle produced no output')

// Purity gate: every runtime require must be a module the table provides.
const required = new Set()
for (const match of bundled.matchAll(/require\("([^"]+)"\)/g)) {
  if (match[1] !== undefined) required.add(match[1])
}
const unexpected = [...required].filter(target => !EXTERNALS.includes(target))
if (unexpected.length > 0) {
  throw new Error(`client bundle requires non-external modules: ${unexpected.join(', ')}`)
}

const wrapped = `/**
 * ${pkg.name} v${pkg.version} — browser half (generated by scripts/build-client.mjs).
 * Registers the "DSH 配置与插件同步 / DSH Config & Plugin Sync" settings section.
 * Do not edit by hand; edit client/src/** and rebuild.
 */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${indent(bundled, 4)}
    var value = module.exports && module.exports.default !== undefined ? module.exports.default : module.exports;
    return value;
  },
});
`

await mkdir(dirname(outfile), { recursive: true })
await writeFile(outfile, wrapped, 'utf8')
console.log(
  `[build-client] wrote ${outfile} (${wrapped.length} bytes; externals: ${[...required].sort().join(', ') || 'none'})`,
)

/** Indent every non-empty line by `n` spaces so the bundle stays readable. */
function indent(text, n) {
  const pad = ' '.repeat(n)
  return text
    .split('\n')
    .map(line => (line.length === 0 ? line : pad + line))
    .join('\n')
}
